#include <Arduino.h>
#include <string.h>
#include "ccmp.h"

void setup() {
    Serial.begin(115200);
    // PUBLIC IEEE test vector 1, also reproduced by FreeBSD net80211.
    const uint8_t key[16]={0xc9,0x7c,0x1f,0x67,0xce,0x37,0x11,0x85,
        0x51,0x4a,0x8a,0x19,0xf2,0xbd,0xd5,0x2f};
    const uint8_t header[24]={0x08,0x48,0xc3,0x2c,0x0f,0xd2,0xe1,0x28,
        0xa5,0x7c,0x50,0x30,0xf1,0x84,0x44,0x08,0xab,0xae,0xa5,0xb8,0xfc,0xba,0x80,0x33};
    const uint8_t plain[20]={0xf8,0xba,0x1a,0x55,0xd0,0x2f,0x85,0xae,0x96,0x7b,
        0xb6,0x2f,0xb6,0xcd,0xa8,0xeb,0x7e,0x78,0xa0,0x50};
    const uint8_t encrypted[36]={0x0c,0xe7,0,0x20,0x76,0x97,0x03,0xb5,
        0xf3,0xd0,0xa2,0xfe,0x9a,0x3d,0xbf,0x23,0x42,0xa6,0x43,0xe4,
        0x32,0x46,0xe8,0x0c,0x3c,0x04,0xd0,0x19,0x78,0x45,0xce,0x0b,0x16,0xf9,0x76,0x23};
    CcmpEpoch tx{},rx{};
    memcpy(tx.key,key,16);memcpy(tx.receiver,header+4,6);
    memcpy(tx.transmitter,header+10,6);memcpy(tx.bssid,header+16,6);
    rx=tx;tx.tx_pn=0xb5039776e70bULL;
    uint8_t frame[60], recovered[20];
    bool ok=ccmp_seal(&tx,header,plain,20,frame,sizeof(frame))==60 &&
        !memcmp(frame+24,encrypted,36) &&
        ccmp_open(&rx,frame,60,recovered,20)==20 && !memcmp(recovered,plain,20) &&
        ccmp_open(&rx,frame,60,recovered,20)==-1;
    Serial.printf("CCMP public-vector selftest: %s; ALL RADIOS OFF; RSN handshake NOT IMPLEMENTED\n",ok?"PASS":"FAIL");
}
void loop() { delay(1000); }
